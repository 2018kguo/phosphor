// Command unicodegen regenerates the Unicode 17 terminal emoji tables.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"strconv"
	"strings"
)

func main() {
	widths := flag.String("widths", "", "native oracle width-table JSONL; regenerate scalar widths instead of emoji properties")
	flag.Parse()
	if *widths != "" {
		emitWidths(*widths)
		return
	}
	const root = "https://www.unicode.org/Public/17.0.0/ucd/"
	var out bytes.Buffer
	out.WriteString("// Code generated by go run ./internal/unicodegen; DO NOT EDIT.\n// Unicode 17; Copyright Unicode, Inc.; see testdata/conformance/LICENSE.unicode.\npackage phosphor\n\n")
	variation := fetch(root+"emoji/emoji-variation-sequences.txt", "bb3d09ef03f206012c7532dd52dc0a21c9efddba0135ea4cf0d9201b8b9bba7e")
	emit(&out, "emojiVariationBases", variation, func(fields []string) bool { return len(fields) >= 2 && fields[1] == "FE0E" })
	emoji := fetch(root+"emoji/emoji-data.txt", "2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b")
	for _, spec := range []struct{ name, property string }{{"emojiModifierBases", "Emoji_Modifier_Base"}, {"emojiPictographs", "Extended_Pictographic"}} {
		emit(&out, spec.name, emoji, func(fields []string) bool { return len(fields) == 3 && fields[1] == ";" && fields[2] == spec.property })
	}
	breaks := fetch(root+"auxiliary/GraphemeBreakProperty.txt", "d6b51d1d2ae5c33b451b7ed994b48f1f4dc62b2272a5831e7fd418514a6bae89")
	emit(&out, "graphemeControls", breaks, func(fields []string) bool { return len(fields) == 3 && fields[1] == ";" && fields[2] == "Control" })
	emit(&out, "graphemePrepends", breaks, func(fields []string) bool { return len(fields) == 3 && fields[1] == ";" && fields[2] == "Prepend" })
	derived := fetch(root+"DerivedCoreProperties.txt", "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08")
	emitGraphemeProperties(&out, breaks, emoji, derived)
	formatted, err := format.Source(out.Bytes())
	must(err)
	must(os.WriteFile("grapheme_table.go", formatted, 0644))
}

// The native driver enumerates every Unicode scalar. Requiring its summary
// prevents an accidentally clipped stream or a different Ghostty version from
// silently replacing the terminal's width contract.
func emitWidths(path string) {
	const commit = "6ba144158577d033ccb6ed4b574e4013957c9161"
	f, err := os.Open(path)
	must(err)
	defer f.Close()
	type record struct {
		Kind          string `json:"kind"`
		First, Last   int
		Width         int    `json:"ghostty_width"`
		Commit        string `json:"ghostty_commit"`
		Version       string `json:"unicode_version"`
		Scalars       int    `json:"unicode_scalars"`
		Default       int    `json:"default_width"`
		ExcludedFirst int    `json:"excluded_first"`
		ExcludedLast  int    `json:"excluded_last"`
		NonDefault    int    `json:"non_default_scalars"`
	}
	var ranges []record
	complete := false
	nonDefault := 0
	d := json.NewDecoder(f)
	for {
		var row record
		err := d.Decode(&row)
		if err == io.EOF {
			break
		}
		must(err)
		if complete {
			panic("data follows native width summary")
		}
		switch row.Kind {
		case "native_scalar_width_range":
			if row.First < 0 || row.Last > 0x10ffff || row.First > row.Last || row.Width != 0 && row.Width != 2 || row.First <= 0xdfff && row.Last >= 0xd800 {
				panic("invalid native scalar width range")
			}
			if len(ranges) > 0 && ranges[len(ranges)-1].Last >= row.First {
				panic("overlapping native scalar width ranges")
			}
			ranges = append(ranges, row)
			nonDefault += row.Last - row.First + 1
		case "native_scalar_width_summary":
			if row.Commit != commit || row.Version != "18.0.0" || row.Scalars != 1112064 || row.First != 0 || row.Last != 0x10ffff || row.Default != 1 || row.ExcludedFirst != 0xd800 || row.ExcludedLast != 0xdfff || row.NonDefault != nonDefault {
				panic("unexpected native Unicode width coverage")
			}
			complete = true
		default:
			panic("unexpected native Unicode width record: " + row.Kind)
		}
	}
	if !complete || len(ranges) == 0 {
		panic("incomplete native Unicode width stream")
	}
	// Pack 256 codepoints into eight words, with two bits per width.
	// Identical pages share an index, including large narrow/wide planes.
	var pages [0x1100][8]uint64
	for i := range pages {
		for j := range pages[i] {
			pages[i][j] = 0x5555555555555555 // default width one
		}
	}
	for _, r := range ranges {
		for cp := r.First; cp <= r.Last; cp++ {
			word, shift := cp>>5&7, uint(cp&31)*2
			pages[cp>>8][word] = pages[cp>>8][word] & ^(uint64(3)<<shift) | uint64(r.Width)<<shift
		}
	}
	index := make(map[[8]uint64]int)
	var unique [][8]uint64
	var ids [0x1100]int
	for i, page := range pages {
		id, ok := index[page]
		if !ok {
			id = len(unique)
			index[page] = id
			unique = append(unique, page)
		}
		ids[i] = id
	}
	idType, idBytes := "uint8", 1
	if len(unique) > 256 {
		idType, idBytes = "uint16", 2
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by go run ./internal/unicodegen -widths <native-widths.jsonl>; DO NOT EDIT.\n// Source: Ghostty %s, Unicode 18.0.0, ghostty_unicode_codepoint_width.\n// Enumerates every Unicode scalar; omitted and invalid scalars have width 1.\n// %d deduplicated 256-scalar pages; %d bytes of static lookup data.\n// Unicode data copyright Unicode, Inc.; see testdata/conformance/LICENSE.unicode.\npackage phosphor\n\nvar scalarWidthPageIDs = [0x1100]%s{\n", commit, len(unique), len(ids)*idBytes+len(unique)*64, idType)
	for i, id := range ids {
		fmt.Fprintf(&out, "%d,", id)
		if i%32 == 31 {
			out.WriteByte('\n')
		}
	}
	out.WriteString("}\n\nvar scalarWidthPages = [...][8]uint64{\n")
	for _, page := range unique {
		out.WriteByte('{')
		for _, word := range page {
			fmt.Fprintf(&out, "0x%016X,", word)
		}
		out.WriteString("},\n")
	}
	out.WriteString("}\n")
	formatted, err := format.Source(out.Bytes())
	must(err)
	must(os.WriteFile("scalar_width_table.go", formatted, 0644))
}

func fetch(url, expected string) []byte {
	response, err := http.Get(url)
	must(err)
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		panic(response.Status)
	}
	data, err := io.ReadAll(response.Body)
	must(err)
	if sum := fmt.Sprintf("%x", sha256.Sum256(data)); sum != expected {
		panic("Unicode source checksum changed: " + sum)
	}
	return data
}

func emit(out *bytes.Buffer, name string, data []byte, keep func([]string) bool) {
	var ranges [][2]uint64
	scanner := bufio.NewScanner(bytes.NewReader(data))
	for scanner.Scan() {
		line, _, _ := strings.Cut(scanner.Text(), "#")
		fields := strings.Fields(line)
		if !keep(fields) {
			continue
		}
		first, last, isRange := strings.Cut(fields[0], "..")
		lo, err := strconv.ParseUint(first, 16, 32)
		must(err)
		hi := lo
		if isRange {
			hi, err = strconv.ParseUint(last, 16, 32)
			must(err)
		}
		if len(ranges) > 0 && lo <= ranges[len(ranges)-1][1]+1 {
			ranges[len(ranges)-1][1] = max(hi, ranges[len(ranges)-1][1])
		} else {
			ranges = append(ranges, [2]uint64{lo, hi})
		}
	}
	must(scanner.Err())
	if len(ranges) == 0 {
		panic("empty Unicode property: " + name)
	}
	fmt.Fprintf(out, "var %s = [...][2]rune{\n", name)
	for _, r := range ranges {
		fmt.Fprintf(out, "{0x%X,0x%X},\n", r[0], r[1])
	}
	out.WriteString("}\n\n")
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}

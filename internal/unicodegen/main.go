// Command unicodegen regenerates the terminal's fused Unicode properties.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
)

type unicodeSource struct{ URL, SHA256 string }
type unicodeManifest struct {
	Version string                   `json:"unicode_version"`
	Sources map[string]unicodeSource `json:"sources"`
	Widths  struct {
		Path, SHA256 string
		Commit       string `json:"ghostty_commit"`
	} `json:"native_widths"`
}

func main() {
	data, err := os.ReadFile("internal/unicodegen/sources.json")
	must(err)
	var manifest unicodeManifest
	must(json.Unmarshal(data, &manifest))
	if manifest.Version != "18.0.0" || manifest.Widths.Commit == "" {
		panic("invalid Unicode source manifest")
	}
	source := func(name string) []byte {
		spec := manifest.Sources[name]
		if spec.URL == "" || len(spec.SHA256) != 64 {
			panic("missing Unicode source: " + name)
		}
		return fetch(spec.URL, spec.SHA256)
	}
	variation, emoji, breaks, derived := source("variation"), source("emoji"), source("grapheme_break"), source("conjunct_break")
	data, err = os.ReadFile(manifest.Widths.Path)
	must(err)
	checkSum(data, manifest.Widths.SHA256)
	widths := nativeWidths(data, manifest.Widths.Commit, manifest.Version)
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by go run ./internal/unicodegen; DO NOT EDIT.\n// Unicode %s; width source Ghostty %s.\n// Inputs and checksums: internal/unicodegen/sources.json.\n// Unicode data copyright Unicode, Inc.; see testdata/conformance/LICENSE.unicode.\npackage phosphor\n\n", manifest.Version, manifest.Widths.Commit)
	emitCodepointProperties(&out, breaks, emoji, derived, variation, widths)
	formatted, err := format.Source(out.Bytes())
	must(err)
	must(os.WriteFile("codepoint_table.go", formatted, 0644))
}

func fetch(url, expected string) []byte {
	response, err := http.Get(url)
	must(err)
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		panic(response.Status)
	}
	data, err := io.ReadAll(response.Body)
	must(err)
	checkSum(data, expected)
	return data
}

func checkSum(data []byte, expected string) {
	if sum := fmt.Sprintf("%x", sha256.Sum256(data)); sum != expected {
		panic("Unicode source checksum changed: " + sum)
	}
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}

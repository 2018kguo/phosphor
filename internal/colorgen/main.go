// Command colorgen regenerates the X11 color names from the pinned source.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
	"time"
)

const commit = "46e9dc9a927b2e7e7cba79e6902c176127dbdf2c"
const source = "https://raw.githubusercontent.com/ghostty-org/ghostty/" + commit + "/src/terminal/res/rgb.txt"
const digest = "f8e3a7bea17acc0b91e6285c5d32001db27d84c4461c655afdbce9dbeb4fb6f0"

func main() {
	local := flag.String("source", "", "local rgb.txt (must match the pinned checksum)")
	flag.Parse()
	var data []byte
	var err error
	if *local != "" {
		data, err = os.ReadFile(*local)
		must(err)
	} else {
		client := http.Client{Timeout: 30 * time.Second}
		response, err := client.Get(source)
		must(err)
		defer response.Body.Close()
		if response.StatusCode != http.StatusOK {
			panic(response.Status)
		}
		data, err = io.ReadAll(io.LimitReader(response.Body, 1<<20))
		must(err)
	}
	if fmt.Sprintf("%x", sha256.Sum256(data)) != digest {
		panic("X11 color source checksum differs")
	}
	colors := make(map[string][3]uint8)
	lines := bufio.NewScanner(bytes.NewReader(data))
	for lines.Scan() {
		line := lines.Text()
		if len(line) < 13 {
			panic("short X11 color line")
		}
		var rgb [3]uint8
		for i := range rgb {
			v, err := strconv.ParseUint(strings.TrimSpace(line[4*i:4*i+3]), 10, 8)
			must(err)
			rgb[i] = uint8(v)
		}
		name := strings.ToLower(strings.TrimSpace(line[12:]))
		if old, ok := colors[name]; ok && old != rgb {
			panic("conflicting X11 color aliases")
		}
		colors[name] = rgb
	}
	must(lines.Err())
	keys := make([]string, 0, len(colors))
	for key := range colors {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by go run ./internal/colorgen; DO NOT EDIT.\n// X11 rgb.txt from Ghostty %s; SHA256 %s.\n// Source: %s\n// Copyright The Open Group and Oracle; see licenses/X11.txt.\npackage phosphor\n\n", commit, digest, source)
	out.WriteString("var x11ColorNames = [...]struct { name string; color RGB }{\n")
	for _, key := range keys {
		c := colors[key]
		fmt.Fprintf(&out, "{%q, RGB{%d,%d,%d}},\n", key, c[0], c[1], c[2])
	}
	out.WriteString("}\n")
	formatted, err := format.Source(out.Bytes())
	must(err)
	must(os.WriteFile("color_names.go", formatted, 0644))
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}
